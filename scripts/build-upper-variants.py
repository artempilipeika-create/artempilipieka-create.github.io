"""Audit 13 current upper donors; preserve prior handle donors for saved projects.
Usage: python scripts/build-upper-variants.py /path/to/uploads
FR3D files are read as data, never executed. Superseded D2 files are excluded.
"""
from fr3d_reader import *
import subprocess
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'backend/v2/cabinet_assets/planner'
a=argparse.ArgumentParser(description=__doc__);a.add_argument('sources',type=Path);args=a.parse_args()
old=json.loads(subprocess.check_output(['node','--input-type=module','-e',"import './backend/v2/cabinet_assets/planner/furniture-core.mjs'; console.log(JSON.stringify(globalThis.MF_FURNITURE_CORE.WALL_PRODUCTION))"],cwd=ROOT))
rows=[];archived=[]
for id,p in old.items():
 row=dict(id=id,source_file=p['source_file'],source_sha256=p['source_sha256'],door_count=len(p['doors']),side=p['doors'][0]['side'] if len(p['doors'])==1 else 'double',filling='dryer' if p.get('dryer') else 'shelves',execution='handles',legacy=True)
 (archived if id=='bazis.877ba2f68d92' else rows).append(row)
files=[p for p in args.sources.glob('ВМД*.fr3d') if ('tip-on' in p.name or 'без ручек' in p.name.lower()) and p.name not in ['ВМД2-600.(Сушка).без ручек.fr3d','ВМД2-600.без ручек.fr3d']]
assert len(files)==12,len(files)
replacement=args.sources/'ВМД2-600.(2).fr3d'
assert hashlib.sha256(replacement.read_bytes()).hexdigest()=='6c187245284ab1651e01e4ff805f554cbedd5fef67ce5d9dabf67fde30351ae7'
files.append(replacement)
def purchase(t):
 counts=collections.Counter();fn={vals(n).get('FastID'):n for n in child(t,'FurnList')['children']}
 def visit(n):
  v=vals(n);ty=v.get('Type')
  if ty==4001:
   counts[v.get('Name','')]+=1
   return # kit children are not separately purchased; also removes its drilling.
  if ty==3001:
   e=fn.get(v.get('FastID'));els=child(child(e,'ParData'),'Elements')['children'] if e else []
   names=[x['value'] for x in els] or [v.get('Name','')]
   for name in names:
    if name and not re.fullmatch(r'[\d.,]+[xх×][\d.,]+',name):counts[name]+=1
  for c in n['children']:visit(c)
 visit(child(t,'Model'))
 return [dict(key='upper-hw-'+str(i+1),name=k.split('\r')[0],article=k.split('\r')[-1] if '\r' in k else None,quantity=v,unit='pcs') for i,(k,v) in enumerate(counts.items())]
for source in sorted(files):
 t=load(source);m=child(t,'Model');sha=hashlib.sha256(source.read_bytes()).hexdigest();panels=[];shelf_rules=[]
 for n,mat,path in walk(m):
  v=vals(n)
  if v.get('Type')==4002 and v.get('Thick',0)>=1:
   p=panelinfo(n,mat,path);panels.append(dict(name=p['name'],lo=p['bounds']['lo'],size=p['bounds']['size']))
  if 'Параметрическая полка' in v.get('Name',''):
   sc=scheme(n)
   if sc:shelf_rules.append(dict(name=v['Name'],rules=rules(sc),mount_direction=vals(sc).get('MountDir',0),parameters={k:v for k,v in vals(sc).items() if k in ['StartIndent','EndIndent','PrimStep','SizeParam','AroundStep']},cached=kit(sc)))
 fronts=[p for p in panels if p['name']=='Фасад'];bottom=next(p for p in panels if p['name']=='Дно');hw=purchase(t)
 count=2 if source.name.startswith('ВМД2') else 1;side='double' if count==2 else 'left' if 'отк L' in source.name else 'right'
 assert len(fronts)==count
 assert sum(h['quantity'] for h in hw if h['article']=='112602')==2*count
 execution='handles' if source==replacement else 'push' if 'tip-on' in source.name else 'handleless'
 assert sum(h['quantity'] for h in hw if h['article']=='09.0019')==(count if execution=='push' else 0)
 rows.append(dict(id='bazis.'+sha[:12],source_file=source.name,source_sha256=sha,door_count=count,side=side,filling='dryer' if 'Сушка' in source.name else 'shelves',execution=execution,legacy=False,native_frame=frame(m),panels=panels,hardware_items=hw,bottom_front_inset_mm=317-bottom['size'][2],facade_clearance_mm=fronts[0]['lo'][2]-320,shelf_rules=shelf_rules))
 if source==replacement:rows[-1]['previous_sources']=archived
assert len({(v['door_count'],v['side'],v['filling'],v['execution']) for v in rows})==18
for v in rows+archived:
 v['label']=f"ВМД{v['door_count']}"+({'left':' L','right':' P','double':''}[v['side']])+(' · Сушка' if v['filling']=='dryer' else ' · Полки')+' · '+{'handles':'Накладные ручки','handleless':'Без ручек','push':'Нажатие (tip-on)'}[v['execution']]
(OUT/'upper-variants.json').write_text(json.dumps(rows,ensure_ascii=False,indent=2)+'\n')
(OUT/'upper-variants.js').write_text('/* Generated by scripts/build-upper-variants.py. */\nglobalThis.MF_UPPER_VARIANTS = '+json.dumps(rows,ensure_ascii=False,separators=(',',':'))+';\n')
print('Audited',len(rows),'upper variants:',len(files),'new sources')
for v in rows:
 if not v['legacy']:print(v['id'],v['label'],'bottom inset',v['bottom_front_inset_mm'],'front clearance',v['facade_clearance_mm'])
