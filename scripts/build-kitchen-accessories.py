"""Extract the six user supplied FR3D files; never execute embedded scripts."""
from fr3d_reader import *
from importlib.machinery import SourceFileLoader
g=SourceFileLoader('gola_reader',str(Path(__file__).with_name('build-gola-variants.py'))).load_module()
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'backend/v2/cabinet_assets/planner'
NAMES={'НМ-600.ПМ.fr3d':('dishwasher','standard'),'НМ-600.ПМ.Gola L.fr3d':('dishwasher','gola'),
 'Цоколь. Прямой.fr3d':('plinth','straight'),'Цоколь. Угловой_Лево.fr3d':('plinth','left'),
 'Цоколь. Угловой_Право..fr3d':('plinth','right'),'Цоколь. П-образ.fr3d':('plinth','u')}
def build(folder):
 rows=[]
 for filename,(kind,variant) in NAMES.items():
  source=folder/filename;t=load(source);m=child(t,'Model');sha=hashlib.sha256(source.read_bytes()).hexdigest()
  row=dict(id='bazis.'+sha[:12],source_file=filename,source_sha256=sha,kind=kind,variant=variant,
   frame=frame(m),model_elastic=planeinfo(child(child(t,'ModelParams'),'Params')),panels=[],profiles=[])
  for n,mat,path in walk(m):
   v=vals(n)
   if v.get('Type')==4002:
    p=g.panel(n,mat,path);p.pop('center');p['key']=('front-' if kind=='dishwasher' else 'plinth-')+str(len(row['panels'])+1)
    p['role']='front' if kind=='dishwasher' else 'plinth';p['material_name']=v.get('Mat','').split('\r')[0];p['material_article']=v.get('Mat','').split('\r')[-1] if '\r' in v.get('Mat','') else None;row['panels'].append(p)
   if v.get('Type')==2004:
    xy=g.poly(v['Contour']);pts=np.array([(mat@[*p,z,1])[:3] for p in xy for z in [0,v['Thickness']]])
    row['profiles'].append(dict(name=v['Name'],material_name=v['Mat'].split('\r')[0],article=v['Mat'].split('\r')[-1],bounds=points_bound(pts),contour_yz=r(np.array([(mat@[*p,0,1])[1:3] for p in xy]))))
  for profile in row['profiles']:
   if profile['article']=='89731':
    variants=json.loads((OUT/'gola-variants.json').read_text())
    ordinary=next(p for v in variants for p in v['profiles'] if p['article']=='60965')
    profile['documentation_profile']={k:ordinary[k] for k in ('article','material_name')}
  rows.append(row)
  dest=OUT/'accessory-sources'/filename;dest.parent.mkdir(exist_ok=True);dest.write_bytes(source.read_bytes())
 (OUT/'accessory-variants.json').write_text(json.dumps(rows,ensure_ascii=False,indent=2)+'\n')
 (OUT/'accessory-variants.js').write_text('/* Generated by scripts/build-kitchen-accessories.py. */\nglobalThis.MF_ACCESSORY_VARIANTS = '+json.dumps(rows,ensure_ascii=False,separators=(',',':'))+';\n')
if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('sources',type=Path);build(ap.parse_args().sources)
